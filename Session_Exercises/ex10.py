# The below line utilizes the tab function "\t" to indent or tab the cursor before it starts the string.
tabby_cat = "\tI'm tabbed in."

# The below line utilized the new line function to separate the first part of the sting from the second part by placing them on two separate lines
persian_cat = "I'm split\non a line."

# The below line utilizes the first backslash function to ignore the following '\' and just print it as a normal character 
backslash_cat = "i'm \\ a \\ cat."

# The below line utilizes the three double quotes to identify the following lines just as they are written. When they are printed out, they are not printed sequentially but are printed just as they are represented here. Note: the tab function is also utilized in this string as well as the new line function
fat_cat = """
I'll do a list:
\t* Cat food
\t* Fishies
\t* Catnip\n\t* Grass
"""

# The below lines are just print functions to output the various variables and to show how those variables are formatted when they are commanded to print
print(tabby_cat)
print(persian_cat)
print(backslash_cat)
print(fat_cat)

